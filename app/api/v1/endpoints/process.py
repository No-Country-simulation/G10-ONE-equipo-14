from fastapi import (
    APIRouter,
    Depends,
    File,
    Form,
    Header,
    HTTPException,
    UploadFile,
    status,
)
from collections import Counter
from time import perf_counter
from sqlalchemy.orm import Session

from app.db.session import get_db
from app.api.security import require_mutation_access
from app.schemas.v1.process import (
    ProcessRequest,
    ProcessResponse,
    RecordErrorResponse,
    RunSummary,
)
from app.services.csv_ingestion import parse_interactions_csv
from app.services.idempotency import (
    IdempotencyConflictError,
    get_or_create_run,
    mark_run_failed,
    save_run_response,
)
from app.services.ingestion import ingest_interactions
from app.services.pipeline import analyze_and_persist
from app.services.content_generation import ContentProviderUnavailable
from app.services.resilient_analysis import (
    AnalysisProviderUnavailable,
    AnalysisRateLimited,
)

router = APIRouter(dependencies=[Depends(require_mutation_access)])


def _response(
    payload: ProcessRequest,
    idempotency_key: str,
    db: Session,
    pre_errors=None,
) -> ProcessResponse:
    try:
        idempotency = get_or_create_run(
            db=db,
            payload=payload,
            idempotency_key=idempotency_key,
        )
    except IdempotencyConflictError as exc:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=str(exc),
        ) from exc
    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=str(exc),
        ) from exc

    run = idempotency.run

    # Same key + same request:
    # return exactly the response generated by the original request.
    if idempotency.replay:
        if run.response_json is not None:
            return ProcessResponse.model_validate(run.response_json)

        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="A request with this Idempotency-Key is already being processed.",
        )

    try:
        processing_started = perf_counter()
        result = ingest_interactions(
            db,
            payload.organization_id,
            payload.community_id,
            payload.interactions,
        )

        all_errors = list(pre_errors or []) + result.errors
        analyses, opportunities, assets, alerts = analyze_and_persist(
            db,
            run.id,
            result.interactions_to_process,
            [asset.value for asset in payload.requested_assets],
        )
        sentiment_counts = Counter(item.sentiment for item in analyses)
        topic_counts = Counter(topic for item in analyses for topic in item.topics)
        predominant_sentiment = (
            sentiment_counts.most_common(1)[0][0] if sentiment_counts else None
        )
        top_topics = [topic for topic, _ in topic_counts.most_common(3)]
        processing_time_ms = round((perf_counter() - processing_started) * 1000, 2)

        response = ProcessResponse(
            schema_version="v1",
            run_id=run.id,
            status=("ACCEPTED" if not all_errors else "ACCEPTED_WITH_ERRORS"),
            organization_id=payload.organization_id,
            community_id=payload.community_id,
            reference_period=payload.reference_period,
            source_name=payload.source_name,
            summary=RunSummary(
                received=result.received + len(pre_errors or []),
                accepted=result.accepted,
                duplicates=result.duplicates,
                reprocessed=result.reprocessed,
                errors=len(all_errors),
                predominant_sentiment=predominant_sentiment,
                top_topics=top_topics,
                processing_time_ms=processing_time_ms,
            ),
            record_errors=[RecordErrorResponse(**vars(error)) for error in all_errors],
            analyses=analyses,
            opportunities=opportunities,
            assets=assets,
            alerts=alerts,
        )

        save_run_response(
            db=db,
            run=run,
            response_json=response.model_dump(mode="json"),
            status=response.status,
        )

        return response

    except AnalysisRateLimited as exc:
        mark_run_failed(db, run)
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=(
                "Gemini respondió 429 por un límite de solicitudes, tokens o cuota. "
                "Esperá antes de reintentar y, si persiste, revisá los límites del "
                "proyecto en Google AI Studio."
            ),
        ) from exc
    except (AnalysisProviderUnavailable, ContentProviderUnavailable) as exc:
        mark_run_failed(db, run)
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=(
                "El servicio de IA no está disponible temporalmente. "
                "La carga no se procesó; reintentá cuando Gemini vuelva a estar disponible."
            ),
        ) from exc
    except Exception:
        mark_run_failed(db, run)
        raise


@router.post(
    "/process",
    response_model=ProcessResponse,
    status_code=status.HTTP_202_ACCEPTED,
)
def process_json(
    payload: ProcessRequest,
    idempotency_key: str = Header(..., alias="Idempotency-Key"),
    db: Session = Depends(get_db),
) -> ProcessResponse:
    return _response(
        payload=payload,
        idempotency_key=idempotency_key,
        db=db,
    )


@router.post(
    "/process/csv",
    response_model=ProcessResponse,
    status_code=status.HTTP_202_ACCEPTED,
)
async def process_csv(
    file: UploadFile = File(...),
    organization_id: str = Form(...),
    community_id: str = Form(...),
    reference_period: str = Form(...),
    requested_assets: str = Form("LINKEDIN,FAQ"),
    idempotency_key: str = Header(..., alias="Idempotency-Key"),
    db: Session = Depends(get_db),
) -> ProcessResponse:
    if not file.filename or not file.filename.lower().endswith(".csv"):
        raise HTTPException(
            status_code=status.HTTP_415_UNSUPPORTED_MEDIA_TYPE,
            detail="A .csv file is required",
        )

    content = await file.read()
    items, parse_errors = parse_interactions_csv(content)

    if not items and parse_errors:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=[vars(error) for error in parse_errors],
        )

    assets = [
        asset.strip().upper() for asset in requested_assets.split(",") if asset.strip()
    ]

    payload = ProcessRequest(
        organization_id=organization_id,
        community_id=community_id,
        reference_period=reference_period,
        source_name=file.filename,
        requested_assets=assets,
        interactions=items,
    )

    return _response(
        payload=payload,
        idempotency_key=idempotency_key,
        db=db,
        pre_errors=parse_errors,
    )
